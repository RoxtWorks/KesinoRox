    Low1to18,   // 1:1
    High19to36, // 1:1
    Dozen1,     // 1-12, 2:1
    Dozen2,     // 13-24, 2:1
    Dozen3,     // 25-36, 2:1
    Column1,    // 2:1
    Column2,    // 2:1
    Column3,    // 2:1
}
